// Writes api/_lib/caps.ts: the most a flawless player could have knocked off, banished and scored by each point in a
// run, per mode, with headroom (tools/oracle.ts plays the runs). Run it again whenever PACE or RULES change:
//   node tools/make_caps.mjs
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = await build({ entryPoints: [join(root, 'tools/oracle.ts')], bundle: true, format: 'esm', platform: 'node', write: false });
const { ceiling } = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`);

const SECONDS = 1800, EVERY = 15, RUNS = 60;
// headroom over the flawless runs, and the heart ghosts they never see: at most one every 11 s while missing a heart,
// each a symbol, a ghost and up to 50 + 50 points
const headroom = (p) => {
  const hearts = p.t / 11 + 1;
  return {
    symbols: Math.ceil(p.symbols * 1.3 + 10 + hearts),
    ghosts: Math.ceil(p.ghosts * 1.3 + 8 + hearts),
    score: Math.ceil((p.score * 1.5 + 500 + hearts * 100) / 10) * 10,
  };
};
const table = {};
for (const mode of ['mouse', 'hands']) {
  const rows = ceiling(mode, SECONDS, RUNS, EVERY).map(headroom);
  // never lower later on
  for (let i = 1; i < rows.length; i++) for (const k of ['symbols', 'ghosts', 'score']) rows[i][k] = Math.max(rows[i][k], rows[i - 1][k]);
  table[mode] = { symbols: rows.map(r => r.symbols), ghosts: rows.map(r => r.ghosts), score: rows.map(r => r.score) };
  console.log(mode, 'at 1, 5, 30 min:', [4, 20, 120].map(i => rows[i]));
}

writeFileSync(join(root, 'api/_lib/caps.ts'), `/* Generated by tools/make_caps.mjs: don't edit. The most a flawless player could have knocked off, banished and
   scored, with headroom, every ${EVERY} s of a run from 0 to ${SECONDS} s, per mode. Past the end it carries on at the last
   stretch's rate. */
export const CAPS = {
  every: ${EVERY},
${Object.entries(table).map(([m, s]) => `  ${m}: {\n${Object.entries(s).map(([k, v]) => `    ${k}: [${v.join(', ')}],`).join('\n')}\n  },`).join('\n')}
};
`);
console.log('wrote api/_lib/caps.ts');
